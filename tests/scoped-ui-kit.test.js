'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const directory=path.resolve(__dirname,'../dashboard/vendor/tabler-1.6.1');
const metadata=JSON.parse(fs.readFileSync(path.join(directory,'manifest.json'),'utf8'));
const source=fs.readFileSync(path.join(directory,'package/dist/css/tabler.min.css'),'utf8');
const css=fs.readFileSync(path.join(directory,'tabler.scoped.css'),'utf8');
const hash=text=>crypto.createHash('sha256').update(text).digest('hex');
assert.equal(metadata.version,'1.6.1');assert.equal(metadata.license,'MIT');
assert.equal(hash(source),metadata.source_css_sha256);assert.equal(hash(css),metadata.scoped_css_sha256);
assert.equal(metadata.runtime_network,false);assert.equal(metadata.scope,'.wos-kit');
assert.match(css,/@scope \(\.wos-kit\)/);assert.ok(!css.includes('@import'));
assert.ok([...css.matchAll(/url\(([^)]+)\)/g)].every(m=>m[1].replace(/^["']/,'').startsWith('data:')),'no external kit assets');
assert.match(fs.readFileSync(path.join(directory,'LICENSE'),'utf8'),/Permission is hereby granted/);
const index=fs.readFileSync(path.resolve(__dirname,'../dashboard/index.html'),'utf8');
assert.ok(index.includes('/dashboard/vendor/tabler-1.6.1/tabler.scoped.css?v=1'));
assert.ok(!index.includes('cdn.jsdelivr.net/npm/@tabler'),'no runtime CDN');
const script=fs.readFileSync(path.resolve(__dirname,'../dashboard/wos-ui-kit.js'),'utf8');
assert.ok(!/\b(fetch|XMLHttpRequest|WebSocket)\b/.test(script));
assert.ok(!/token|cookie|sessionStorage|localStorage/.test(script),'kit has no secret/session/store access');
assert.ok(!script.includes("'navbar-vertical'"),'preserve existing proven phone drawer rather than override it');
console.log('Pinned MIT kit hashes/license, native scope, no external assets/network/secrets, and retained drawer controls passed. Actual component/theme/click proof remains in full dashboard suites.');
