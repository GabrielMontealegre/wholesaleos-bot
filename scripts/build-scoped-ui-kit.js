'use strict';
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const {launchChromiumWithResolvedBrowser}=require('../modules/research/playwright-browser-resolver');
async function build(){
  const directory=path.resolve(__dirname,'../dashboard/vendor/tabler-1.6.1');
  const source=fs.readFileSync(path.join(directory,'package/dist/css/tabler.min.css'),'utf8');
  if(!source.includes('Tabler v1.6.1'))throw Error('kit_version_mismatch');
  let browser;
  try{
    browser=(await launchChromiumWithResolvedBrowser(require('playwright'),{headless:true})).browser;
    const page=await browser.newPage();
    const parsed=await page.evaluate(source=>{
      const sheet=new CSSStyleSheet();sheet.replaceSync(source);
      let roots=0;
      function visit(rule){
        if(rule.type===CSSRule.IMPORT_RULE)throw Error('kit_runtime_import_not_allowed');
        if(rule.selectorText&&rule.selectorText.includes(':root')){rule.selectorText=rule.selectorText.replaceAll(':root',':scope');roots++;}
        if(rule.cssRules)for(const child of rule.cssRules)visit(child);
      }
      for(const rule of sheet.cssRules)visit(rule);
      if(!roots)throw Error('kit_tokens_missing');
      const scoped=new CSSStyleSheet();scoped.replaceSync('@scope (.wos-kit) { '+[...sheet.cssRules].map(r=>r.cssText).join('\n')+' }');
      if(scoped.cssRules.length!==1||!scoped.cssRules[0].cssText.startsWith('@scope'))throw Error('kit_scope_not_supported');
      return scoped.cssRules[0].cssText.split('\n').map(line=>line.trimEnd()).join('\n');
    },source);
    const header='/*! Tabler1.6.1 - MIT - Copyright2018-2026 The Tabler Authors. See LICENSE. Generated by scripts/build-scoped-ui-kit.js. */\n';
    fs.writeFileSync(path.join(directory,'tabler.scoped.css'),header+parsed+'\n');
    fs.writeFileSync(path.join(directory,'manifest.json'),JSON.stringify({name:'@tabler/core',version:'1.6.1',license:'MIT',source_url:'https://registry.npmjs.org/@tabler/core/-/core-1.6.1.tgz',integrity:'sha512-lgmR9gcxRp5JlLxcmRi9Rz85JrEvH6Bz71KnlcPVSa97wtwQNjgSs3g3fxwbAlulHyRMghhIV04QUuW3pqDsIg==',source_css_sha256:crypto.createHash('sha256').update(source).digest('hex'),scoped_css_sha256:crypto.createHash('sha256').update(header+parsed+'\n').digest('hex'),scope:'.wos-kit',runtime_network:false},null,2)+'\n');
    console.log('Pinned Tabler1.6.1 parsed with CSSOM and scoped to .wos-kit; no runtime CDN.');
  }finally{if(browser)await browser.close();}
}
if(require.main===module)build().catch(e=>{console.error(e.message);process.exitCode=1;});
module.exports={build};
